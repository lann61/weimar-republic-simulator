type Extra = Partial<Person> & { party_from?: string | null };

/**
 * 真实历史人物数据库（方案 §26）
 * 原则：
 * - 只录入真实人物，不编造姓名、职务或党籍。
 * - 生日/忌日无法确证到日时，仅写年份，不虚构日期精度。
 * - 党籍按时间记录；跨党者分段保存。
 * - 心理属性一律不录入；模拟参数单独存放（simulation_parameters）。
 */
function P(
  id: string,
  zh: string,
  de: string,
  birth: string,
  death: string,
  party: string | null,
  roles: string[],
  summary: string,
  extra: Extra = {}
): Person {
  const activeFrom = extra.active_period?.from ?? (birth.length === 4 ? `${birth}-01-01` : birth);
  return {
    id,
    name_zh: zh,
    name_de: de,
    birth_date: birth,
    death_date: death,
    is_historical_person: true,
    active_period: { from: activeFrom, to: extra.active_period?.to ?? (death.length === 4 ? `${death}-12-31` : death) },
    roles,
    // WMR-011：党籍起始日期与出生日期分离；无可靠史料时标 null（显示“日期未核实”），不伪造
    party_memberships: party
      ? [{ party_id: party, from: extra.party_from ?? null, to: null, source_ids: [...SRC_WH, ...SRC_RT] }]
      : [],
    offices: [],
    portrait_asset: null,
    historical_summary: summary,
    simulation_parameters: { status: 'not_calibrated', notes: '行为参数未校准；仅使用公开立场、投票记录与职务关系。' },
    source_ids: [...SRC_WH],
    data_quality: 'historical_secondary',
    ...extra,
  };
}

