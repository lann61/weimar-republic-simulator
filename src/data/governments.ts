function buildGov(s: GovSpec): Government {
  const members: CabinetMember[] = s.members.map(([person, office, party, identity, to, from]) => ({
    person_id: person,
    office_id: office,
    office_zh: OFFICE_LABELS[office] ?? office,
    party_id: party,
    political_identity: identity ?? (party ? 'party' : 'independent_official'),
    from: from ?? s.from,
    to: to === undefined ? s.to : to,
    appointment_mode: 'presidential_appointment',
    cabinet_status: office === 'without_portfolio' ? 'minister_without_portfolio' : 'full_member',
  }));

  return {
    id: s.id,
    name_zh: s.name_zh,
    from: s.from,
    to: s.to,
    chancellor_id: s.chancellor,
    vice_chancellor_id: s.vice ?? null,
    type: s.type,
    parties: s.parties,
    support_parties: s.support ?? [],
    seats_at_formation: s.seats,
    parliament_seats_total: s.total,
    members,
    program_zh: s.program,
    presidential_support: s.presidential,
    parliamentary_trust: s.trust,
    end_reason: s.end_reason,
    is_historical: true,
    historical_summary: s.summary,
    source_ids: ['source_dhm_cabinets', 'source_bundestag_chancellors'],
    data_quality: 'historical_secondary',
    notes: '内阁名单覆盖主要职务；个别次要部长与兼任关系待以档案逐项核验，未录入的职务不虚构补全。',
  };
}

export const governments: Government[] = specs.map(buildGov);
export const governmentMap = new Map(governments.map((g) => [g.id, g]));
